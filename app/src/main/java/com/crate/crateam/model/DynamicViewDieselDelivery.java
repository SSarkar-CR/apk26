package com.crate.crateam.model;

public class DynamicViewDieselDelivery {
    private String item_fulled;
    private String item_plant_no;
    private String liters_fulled;
    private String general_comment;
    public DynamicViewDieselDelivery(){

    }

    public String getItem_fulled() {
        return item_fulled;
    }
    public void setItem_fulled(String item_fulled) {
        this.item_fulled = item_fulled;
    }
    public String getItem_plant_no() {
        return item_plant_no;
    }
    public void setItem_plant_no(String item_plant_no) {
        this.item_plant_no = item_plant_no;
    }
    public String getLiters_fulled() {
        return liters_fulled;
    }
    public void setLiters_fulled(String liters_fulled) {
        this.liters_fulled = liters_fulled;
    }
    public String getGeneral_comment() {
        return general_comment;
    }
    public void setGeneral_comment(String general_comment) {
        this.general_comment = general_comment;
    }
}
